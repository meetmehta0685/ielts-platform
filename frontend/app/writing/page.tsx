    e?.preventDefault();
    if (!token) {
      toast.error("Session expired. Please log in again.");
      return;
    }

    if (prompt.trim().length < 10) {
      toast.error("Please enter a valid prompt (minimum 10 characters).");
      return;
    }

    const minWords = taskType === "task1" ? 50 : 100;
    if (wordCount < minWords) {
      toast.error(`Your response is too short. Minimum word limit for analysis is ${minWords} words.`);
      return;
    }

    setIsGrading(true);
    setResult(null);
    setStreamingText("");
